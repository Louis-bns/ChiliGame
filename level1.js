// level1.js

(function () {
  const COLS = 45;
  const ROWS = 45;

  // Grid aufbauen
  const grid = Array.from({ length: ROWS }, () => Array(COLS).fill("0"));

  const wall = (x, y) => {
    if (x < 0 || y < 0 || x >= COLS || y >= ROWS) return;
    grid[y][x] = "1";
  };

  const hLine = (x1, x2, y) => {
    const a = Math.min(x1, x2), b = Math.max(x1, x2);
    for (let x = a; x <= b; x++) wall(x, y);
  };

  const vLine = (x, y1, y2) => {
    const a = Math.min(y1, y2), b = Math.max(y1, y2);
    for (let y = a; y <= b; y++) wall(x, y);
  };

  const rect = (x1, y1, x2, y2) => {
    hLine(x1, x2, y1);
    hLine(x1, x2, y2);
    vLine(x1, y1, y2);
    vLine(x2, y1, y2);
  };

  /* -------------------------
     1) Außenrahmen 45×45
     ------------------------- */
  rect(0, 0, COLS - 1, ROWS - 1);

  /* -------------------------
     2) Wände nach deiner Vorlage (im 32×32 Bereich)
     Koordinaten sind 0-based Tiles.
     ------------------------- */

  // Großer "Block" links (ungefähr wie im Bild)
  // Linker Kasten
  rect(2, 16, 10, 23);
  // Verbindung nach unten links
  vLine(6, 23, 31);
  hLine(0, 6, 31);

  // Oberer Gang links/oben
  vLine(4, 13, 16);
  hLine(4, 18, 7);
  vLine(18, 0, 7);

  // Mittlere „Brücke“ oben (lange horizontale Wand)
  hLine(6, 18, 3);
  vLine(6, 3, 7);

  // Zentrum-Rechts: Spawn-Raum (Rechteck um das X)
  // (X liegt ungefähr bei x≈18, y≈16 im Bild)
  rect(15, 13, 22, 19);

  // Rechter Gang / großer Bereich rechts
  // Obere Linie vom Spawnraum nach rechts
  hLine(22, 32, 17);
  // Rechte Außenwand im 32er Bereich nach unten
  vLine(32, 6, 30);
  // Untere Linie zurück nach links
  hLine(15, 32, 30);

  // Unterer „Korridor“ (wie im Bild die lange Wand unten rechts)
  hLine(15, 36, 36);
  vLine(15, 30, 36);

  // Innenknick rechts (die "Einbuchtung" im rechten Bereich)
  vLine(27, 19, 26);
  hLine(22, 27, 26);

  /* -------------------------
     3) Export
     ------------------------- */
  window.LEVEL1 = {
    id: "level1",
    cols: COLS,
    rows: ROWS,
    tileSize: 32,

    // Spawn beim schwarzen X (ungefähr mittig im Spawn-Raum)
    spawn: { tx: 18, ty: 16 },

    enemies: { bat: false },

    walls: grid.map((row) => row.join(""))
  };
})();// level1.js – 45×45 Grid
